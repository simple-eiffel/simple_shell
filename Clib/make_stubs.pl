#!/usr/bin/perl
# Writes a half's stubs file: a "not available" body (0, NULL or nothing) for every entry
# point shell_posix.h declares that the half's sources do not define yet, so the Eiffel
# classes always link and each stub disappears as soon as its real body is written.
# The stubs file goes in the half's folder (macos/ or linux/), next to its sources.
# Usage: make_stubs.pl shell_posix.h <the half's .m or .c files> > <half>/<name>_stubs.c
use strict; use warnings;
my ($header, @sources) = @ARGV;
my $body = "";
for my $source (@sources) { open my $s, "<", $source or die "$source: $!"; local $/; $body .= <$s>; }
my %defined = map { $_ => 1 } ($body =~ /^[A-Za-z_][\w \*]*?\b(\w+)\s*\([^;{]*\)\s*\{/mg);
open my $h, '<', $header or die "$header: $!";
print "/* Generated by make_stubs.pl from shell_posix.h and the half's sources: do not edit. */\n";
print "#include \"../shell_posix.h\"\n\n";
my $n = 0;
while (<$h>) {
	s/\r$//;   # a CRLF checkout (Windows, or WSL over it) reads the same
	next unless /^((?:unsigned )?[A-Za-z_]+\s*\**)\s*((?:shell|ss)_\w+)\(([^)]*)\);$/;
	my ($ret, $name, $params) = ($1, $2, $3);
	next if $defined{$name};
	(my $r = $ret) =~ s/\s+$//;
	my @names = $params eq 'void' ? () : map { /(\w+)\s*$/ ? $1 : () } split /,/, $params;
	my $unused = join ' ', map { "(void)$_;" } @names;
	my $answer = $r eq 'void' ? '' : ($r =~ /\*|HWND/ ? ' return 0;' : $r eq 'double' ? ' return 0.0;' : ' return 0;');
	print "$r $name($params) { $unused$answer }\n";
	$n++;
}
print STDERR "make_stubs.pl: $n entry points stubbed\n";
